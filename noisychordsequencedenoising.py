# Label mapping (25 classes)
# 12 pitch classes in a canonical order
PITCHES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
FLAT_TO_SHARP = {
    "Db": "C#",
    "Eb": "D#",
    "Gb": "F#",
    "Ab": "G#",
    "Bb": "A#",
    "Cb": "B",
    "Fb": "E",
} # Flat -> sharp normalization map
ROOT_RE = re.compile(r"^([A-G](?:#|b)?)")  # Root extraction regex (handles C, C#, Db, etc.)

def normalize_root(root: str) -> Optional[str]:
    root = root.strip()
    root = FLAT_TO_SHARP.get(root, root)   # Convert flats to sharps
    return root if root in PITCHES else None  # Validate root

def chord_to_25class(chord: str) -> int:
    """
    Map a chord label string to:
      0..11  -> root major
      12..23 -> root minor
      24     -> N (no chord / silence / unknown)
    Notes:
    - We keep ONLY root + (maj/min)
    - Everything else is collapsed into maj/min if possible, else N
    """
    s = chord.strip()
    if s in {"N", "X", "NoChord", "no_chord", "NONE"}:     # Common no-chord tokens
        return 24
    # Some Billboard chord files use formats like "C:maj", "C:min", "C", "C:min7", etc.
    m = ROOT_RE.match(s)   # Extract root token
    if not m:
        return 24
    root_raw = m.group(1)    # Root token (e.g., Db)
    root = normalize_root(root_raw)    # Normalize to sharp if flat
    if root is None:
        return 24
    root_idx = PITCHES.index(root)                          # 0..11 pitch class

    # Decide quality (maj/min)
    s_lower = s.lower()
    is_minor = ("min" in s_lower) and ("maj" not in s_lower)

    # Treat "m" (e.g., "Am") as minor only when safe (avoid "maj")
    if not is_minor:
        # Handle cases like "Am" or "A:m" if present
        if re.search(r"(^|[:\s])m($|[^a-z])", s_lower) and ("maj" not in s_lower):
            is_minor = True

    return (12 + root_idx) if is_minor else root_idx        # Encode maj/min

