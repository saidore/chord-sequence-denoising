def find_good_examples(
    examples,
    noise_type="uniform",
    eps=0.30,
    window=20,
    max_examples=3,
    seed=123
):
    rng = np.random.default_rng(seed)          # Reproducible sampling
    B = emission_uniform(NUM_CLASSES, eps)     # HMM emission matrix
    candidates = []                            # Store candidate snippets

    example_order = list(range(len(examples))) # All song indices
    rng.shuffle(example_order)                 # Shuffle order

    for ex_id in example_order:                # Check each song
        y = examples[ex_id].y                  # Clean sequence
        if len(y) < window:                    # Skip very short songs
            continue

        x = corrupt(y, noise_type=noise_type, eps=eps)      # Corrupt once
        preds = method_predictions_for_sequence(y, x, B)    # Run all methods

        # Try all possible snippet starts
        for start in range(0, len(y) - window + 1):
            end = start + window               # End index

            noisy_acc = snippet_acc(y[start:end], preds["Noisy"][start:end])          # Noisy acc
            hmm_acc = snippet_acc(y[start:end], preds["HMM-Marginal"][start:end])     # HMM acc
            gnn_acc = snippet_acc(y[start:end], preds["GNN-MIX"][start:end])          # GNN acc

            # Score = how informative the snippet is
            score = (hmm_acc - noisy_acc) + (gnn_acc - noisy_acc)  # Combined improvement

            candidates.append({                # Save candidate
                "ex_id": ex_id,
                "start": start,
                "end": end,
                "score": score,
                "y": y,
                "x": x,
                "preds": preds,
            })

    # Sort by best informative score first
    candidates = sorted(candidates, key=lambda d: d["score"], reverse=True)

    # Keep unique songs only
    chosen = []                                # Selected examples
    used_song_ids = set()                      # Avoid repeats from same song
    for cand in candidates:                    # Scan sorted candidates
        if cand["ex_id"] in used_song_ids:     # Skip duplicate songs
            continue
        chosen.append(cand)                    # Keep this one
        used_song_ids.add(cand["ex_id"])       # Mark used
        if len(chosen) >= max_examples:        # Stop after enough examples
            break

    return chosen                              # Return chosen snippets

