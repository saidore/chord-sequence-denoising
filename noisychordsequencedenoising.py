def train_one_epoch(model, loader, optimizer) -> float:
    model.train()
    losses = []
    for batch in loader:  # Iterate each batch
        batch = batch.to(device)
        logits = model(batch)   # Forward pass
        loss = F.cross_entropy(logits, batch.y)  # CE loss
        optimizer.zero_grad()
        loss.backward()  # Backprop
        optimizer.step()
        losses.append(float(loss.item()))
    return float(np.mean(losses)) if losses else float("nan")

@torch.no_grad()
def evaluate_fixed_noise(model, examples, eps: float, noise_type: str, batch_size: int = 8):
    model.eval()
    ds = ChordChainDataset(examples, noise_levels=[eps], noise_types=[noise_type], mode="eval")
    loader = DataLoader(ds, batch_size=batch_size, shuffle=False)

    accs, changes = [], []
    for batch in loader:  # Iterate each batch
        batch = batch.to(device)
        logits = model(batch)   # Forward pass
        pred = logits.argmax(dim=-1).cpu().numpy()   # Calculate predictions
        ptr = batch.ptr.cpu().numpy()
        y_true = batch.y.cpu().numpy()

        for i in range(len(ptr) - 1):  # Calculate stats for each batch
            a, b = int(ptr[i]), int(ptr[i + 1])
            yt = y_true[a:b].tolist()  # True labels
            yp = pred[a:b].tolist()  # Predicted labels
            accs.append(accuracy_seq(yt, yp))
            changes.append(change_rate_seq(yp))

    return {"acc": float(np.mean(accs)), "change": float(np.mean(changes)), "num_songs": len(accs)}

