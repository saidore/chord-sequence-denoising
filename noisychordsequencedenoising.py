@dataclass
class SongExample:
    song_id: str   # Unique identifier
    y: List[int]    # Clean beat-level labels

def make_song_id_from_path(p: str) -> str:
    # Use a stable ID from relative path
    return re.sub(r"[^a-zA-Z0-9]+", "_", os.path.splitext(os.path.basename(p))[0])  # Simple ID

def build_sequences_from_kaggle_path(dataset_dir: str,
                                    prefer_beats: bool = True,
                                    fixed_hop_sec: float = 0.5,
                                    max_songs: Optional[int] = None) -> List[SongExample]:
    """
    Tries to build clean sequences for each song from .lab chord segments plus beat times if present.
    If beat files aren't found, falls back to fixed-grid sampling.
    """
    buckets = find_annotation_files(dataset_dir)    # Find candidate files
    lab_files = sorted(buckets["lab"])   # Sort lab files
    beat_files = sorted(buckets["beats"])   # Sort beat files

    # Make a quick lookup for beat files by basename
    beat_map: Dict[str, str] = {}
    for bf in beat_files:
        key = os.path.splitext(os.path.basename(bf))[0].lower()  # Base key
        beat_map[key] = bf   # Store path

    examples: List[SongExample] = []  # Output list
    for lab_path in lab_files:
        segs = read_lab_segments(lab_path)   # Read chord segments
        if not segs:
            continue
        base_key = os.path.splitext(os.path.basename(lab_path))[0].lower()  # Base key
        beats = None

        if prefer_beats and base_key in beat_map:
            beats = read_beat_times(beat_map[base_key])   # Read beats if matched

        if beats is not None:
            y_ids = discretize_to_beats(segs, beats)   # Beat-level labels
        else:
            y_ids = discretize_fixed_grid(segs, hop_sec=fixed_hop_sec)  # Fallback
        if len(y_ids) < 8:
            continue       # Skip too-short sequences

        song_id = make_song_id_from_path(lab_path)     # Create song ID
        examples.append(SongExample(song_id=song_id, y=y_ids))    # Store example

        if max_songs is not None and len(examples) >= max_songs:
            break

    return examples

