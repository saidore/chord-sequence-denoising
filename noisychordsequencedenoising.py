def accuracy_seq(y_true: list[int], y_pred: list[int]) -> float:
    """
    Per-time-step accuracy for one sequence.
    """
    if len(y_true) == 0:
        return float("nan")
    yt = np.array(y_true, dtype=int)   # True labels array
    yp = np.array(y_pred, dtype=int)   # Pred labels array
    return float((yt == yp).mean())   # Fraction correct

def change_rate_seq(y_seq: list[int]) -> float:
    """
    Smoothness/jitter metric: fraction of adjacent steps that change.
    - 0.0 means perfectly constant
    - higher means more jitter / more frequent changes
    """
    if len(y_seq) < 2:
        return 0.0       # No adjacent pairs
    y = np.array(y_seq, dtype=int)
    changes = (y[1:] != y[:-1]).sum()  # Count changes
    return float(changes / (len(y_seq) - 1))  # Normalize by length

