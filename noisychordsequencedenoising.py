@dataclass
class ChordSegment:
    start: float   # Segment start time (sec)
    end: float    # Segment end time (sec)
    label: str      # Chord label string

def read_lab_segments(lab_path: str) -> List[ChordSegment]:
    """
    Reads a .lab file with lines: <start> <end> <label>
    """
    segs: List[ChordSegment] = []    # Output list
    with open(lab_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 3:
                continue     # Skip malformed lines
            start = float(parts[0])  # Parse start time
            end = float(parts[1])      # Parse end time
            label = " ".join(parts[2:])    # Join remaining as label
            segs.append(ChordSegment(start, end, label))    # Store segment
    return segs

def read_beat_times(path: str) -> Optional[np.ndarray]:
    """
    Attempts to read beat times as a 1D array of floats (seconds).
    Accepts simple formats: one beat time per line, or CSV with first column as time.
    """
    try:
        raw = []   # Collect beat times
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                # Take first token; works for "time" or "time,beatnum" formats
                token = re.split(r"[,\s]+", line)[0]
                raw.append(float(token))  # Parse float time
        arr = np.array(raw, dtype=float)
        arr = np.unique(arr)
        arr = np.sort(arr)
        if arr.size < 2:
            return None  # Not enough beats
        return arr
    except Exception:
        return None

# ----------------------------
# Discretize segments to beat-level labels
# ----------------------------
def label_at_time(segments: List[ChordSegment], t: float) -> str:
    """
    Finds chord label active at time t using segment boundaries.
    Assumes segments cover the song; if not, returns 'N'.
    """
    # Linear scan is fine for small lists; can optimize with pointers later
    for seg in segments:
        if seg.start <= t < seg.end:   # Check interval membership
            return seg.label    # Return segment label
    return "N"  # Default if no segment matches

def discretize_to_beats(segments: List[ChordSegment], beats: np.ndarray) -> List[int]:
    """
    Converts chord segments -> one chord label per beat interval.
    We assign chord based on the chord active at the beat time.
    """
    y_ids: List[int] = []  # Output class IDs
    for bt in beats[:-1]:     # Ignore last beat boundary
        lab = label_at_time(segments, float(bt))    # Get chord at beat time
        y_ids.append(chord_to_25class(lab))     # Map to 25-class ID
    return y_ids

def discretize_fixed_grid(segments: List[ChordSegment], hop_sec: float = 0.5) -> List[int]:
    """
    Fallback if beat times are unavailable: sample at a fixed time grid.
    """
    if not segments:
        return []
    t0 = segments[0].start     # Start time
    t1 = max(seg.end for seg in segments)   # End time
    times = np.arange(t0, t1, hop_sec, dtype=float)   # Uniform grid
    y_ids: List[int] = []  # Output class IDs
    for t in times:
        lab = label_at_time(segments, float(t))     # Get chord label at time
        y_ids.append(chord_to_25class(lab))   # Map to class ID
    return y_ids

# ----------------------------
# Corruption (noise) functions
# ----------------------------
def corrupt_uniform(y: List[int], eps: float, num_classes: int = 25) -> List[int]:
    """
    Uniform flip noise: with prob eps, replace with a random other label.
    """
    y = list(y)
    out = []
    for v in y:
        if np.random.rand() < eps:
            # Sample a different label than v
            cand = np.random.randint(0, num_classes)          # Propose random label
            while cand == v:
                cand = np.random.randint(0, num_classes)      # Resample if same
            out.append(int(cand))   # Add flipped label
        else:
            out.append(int(v))   # Keep original
    return out

def corrupt_burst(y: List[int], eps: float, burst_len_range: Tuple[int, int] = (2, 8),
                  num_classes: int = 25) -> List[int]:
    """
    Burst noise: flip contiguous spans until ~eps fraction of positions are corrupted.
    """
    y = list(y)
    n = len(y)
    target = int(np.ceil(eps * n))    # Target corrupted count
    out = y[:]
    corrupted = np.zeros(n, dtype=bool)    # Track corrupted positions

    while corrupted.sum() < target and n > 0:
        L = np.random.randint(burst_len_range[0], burst_len_range[1] + 1)  # Burst length
        start = np.random.randint(0, n)    # Burst start index
        end = min(n, start + L)       # Burst end index

        for i in range(start, end):
            if corrupted.sum() >= target:
                break      # Stop if target reached
            if corrupted[i]:
                continue      # Skip if already corrupted
            v = out[i]
            cand = np.random.randint(0, num_classes)      # Propose new label
            while cand == v:
                cand = np.random.randint(0, num_classes)      # Ensure different label
            out[i] = int(cand)   # Apply corruption
            corrupted[i] = True    # Mark corrupted

    return out

def corrupt(y: List[int], noise_type: str, eps: float) -> List[int]:
    """
    Wrapper for corruption methods.
    noise_type: 'uniform' or 'burst'
    """
    if noise_type == "uniform":
        return corrupt_uniform(y, eps)                        # Uniform flip
    if noise_type == "burst":
        return corrupt_burst(y, eps)                          # Burst noise
    raise ValueError(f"Unknown noise_type: {noise_type}")

