def evaluate_all_methods_same_noise(
    examples,
    eps,
    noise_type,
    hmm_A,
    gnn_u_model,
    gnn_b_model,
    gnn_mix_model,
    majority_window=5
):
    """
    Corrupt each song ONCE, then evaluate every method on that same x.
    """
    B = emission_uniform(NUM_CLASSES, eps)

    metrics = {
        "none": [],
        "spike": [],
        "majority": [],
        "hmm_viterbi": [],
        "hmm_marginal": [],
        "gnn_u": [],
        "gnn_b": [],
        "gnn_mix": [],
    }

    for ex in examples:
        y = ex.y
        x = corrupt(y, noise_type=noise_type, eps=eps)

        # Baselines
        y_none = x
        y_spike = denoise_spike_removal(x)
        y_majority = denoise_majority_filter(x, window=majority_window)

        # HMM methods
        y_hmm_vit = viterbi_decode(
            x,
            A=hmm_A,
            B=B,
            pi=pi_final
        )

        gamma = forward_backward_marginals(
            x,
            A=hmm_A,
            B=B,
            pi=pi_final
        )
        y_hmm_mar = decode_from_marginals(gamma)

        # GNN methods
        y_gnn_u = gnn_predict_from_noisy_sequence(gnn_u_model, x)
        y_gnn_b = gnn_predict_from_noisy_sequence(gnn_b_model, x)
        y_gnn_mix = gnn_predict_from_noisy_sequence(gnn_mix_model, x)

        pred_dict = {
            "none": y_none,
            "spike": y_spike,
            "majority": y_majority,
            "hmm_viterbi": y_hmm_vit,
            "hmm_marginal": y_hmm_mar,
            "gnn_u": y_gnn_u,
            "gnn_b": y_gnn_b,
            "gnn_mix": y_gnn_mix,
        }

        for method_name, y_hat in pred_dict.items():
            metrics[method_name].append({
                "acc": accuracy_seq(y, y_hat),
                "change": change_rate_seq(y_hat),
            })

    rows = []
    for method_name, vals in metrics.items():
        accs = [v["acc"] for v in vals]
        chgs = [v["change"] for v in vals]

        rows.append({
            "noise_type": noise_type,
            "eps": eps,
            "method": method_name,
            "acc_mean": float(np.mean(accs)),
            "acc_std": float(np.std(accs)),
            "change_mean": float(np.mean(chgs)),
            "change_std": float(np.std(chgs)),
            "num_songs": len(vals),
        })

    return rows

