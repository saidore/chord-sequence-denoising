"""## Heuristic Denoise Baselines"""

# Simple smoothing heuristic baselines (fast)
# - Adds 2 cheap denoisers that use only local consistency (no learning, no probabilities):
#     (A) Spike removal: replace single-point spikes (A B A -> A A A)
#     (B) Majority filter: sliding window majority vote (odd window size)
# - Evaluates accuracy + smoothness vs clean labels under uniform + burst noise

# ----------------------------
# Heuristic denoisers
# ----------------------------
def denoise_spike_removal(x: list[int]) -> list[int]:
    """
    Replace isolated spikes:
      if x[t-1] == x[t+1] and x[t] != x[t-1], set x[t] = x[t-1]
    This targets jitter like: 7,19,7  -> 7,7,7
    """
    if len(x) < 3:
        return list(x)    # Too short to smooth
    y = list(x)
    for t in range(1, len(x) - 1):
        left = x[t - 1]   # Left neighbor
        mid = x[t]    # Current
        right = x[t + 1]    # Right neighbor
        if left == right and mid != left:
            y[t] = left    # Remove spike
    return y

def denoise_majority_filter(x: list[int], window: int = 5) -> list[int]:
    """
    Sliding-window majority vote.
    - window must be odd
    - ties break by keeping original x[t]
    """
    if window < 3:
        return list(x)   # No smoothing
    if window % 2 == 0:
        raise ValueError("window must be odd")   # Guard even window

    n = len(x)
    r = window // 2  # Radius
    y = list(x)

    for t in range(n):
        lo = max(0, t - r)  # Window start
        hi = min(n, t + r + 1)     # Window end (exclusive)
        window_vals = x[lo:hi]    # Window slice
        counts = Counter(window_vals)  # Count labels
        best_label, best_count = counts.most_common(1)[0]  # Top label
        # Tie handling: if there is a tie for best_count, keep x[t]
        tied = [lab for lab, cnt in counts.items() if cnt == best_count]
        y[t] = x[t] if len(tied) > 1 else best_label
    return y

