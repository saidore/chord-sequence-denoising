"""## HMM + Viterbi Baseline"""

# HMM baseline + Viterbi (MAP) + Forward-Backward (marginals) + evaluation
# - Learns transition matrix A from TRAIN clean sequences (counts + smoothing)
# - Uses emission/noise matrix B based on the corruption rate eps (uniform flip model)
# - Runs:
#     (1) Viterbi decode (MAP sequence)
#     (2) Forward-Backward marginals (sum-product BP on chain) + per-time argmax decode
# - Evaluates accuracy + smoothness + (for marginals) confidence

# ----------------------------
# Transition matrix estimate: A[j|i] = P(y_t=j | y_{t-1}=i)
# ----------------------------
def estimate_transition_matrix(examples: list, num_states: int = 25, alpha: float = 1.0) -> np.ndarray:
    """
    Estimate a first-order transition matrix from clean sequences using add-alpha smoothing.
    """
    counts = np.zeros((num_states, num_states), dtype=np.float64)     # How many times transition i to j occurs
    for ex in examples:
        y = ex.y      # Clean label sequence for this example
        if len(y) < 2:
            continue
        for t in range(len(y) - 1):  # Count each adjacent pair y[t] -> y[t+1]
            a = int(y[t])    # Previous state
            b = int(y[t + 1])   # Next state
            if 0 <= a < num_states and 0 <= b < num_states:
                counts[a, b] += 1.0   # Count valid states
    counts += alpha        # Add smoothing
    row_sums = counts.sum(axis=1, keepdims=True)     # Normalize rows
    A = counts / np.clip(row_sums, 1e-12, None)
    return A

# ----------------------------
# Emission matrix for uniform-flip corruption: B[y, x] = P(x | y)
# ----------------------------
def emission_uniform(num_states: int, eps: float) -> np.ndarray:
    """
    Uniform flip noise model:
      P(x=y) = 1-eps
      P(x!=y) = eps/(K-1)
    Returns B with shape (K,K) where B[y, x] = P(x | y).
    """
    K = num_states
    B = np.full((K, K), eps / max(K - 1, 1), dtype=np.float64)   # Off-diagonals corruption prob
    np.fill_diagonal(B, 1.0 - eps)   # Diagonal = prob of keeping correct label
    return B

# ----------------------------
# Viterbi decoding (MAP) in log-space
# ----------------------------
def viterbi_decode(x: list[int], A: np.ndarray, B: np.ndarray, pi: np.ndarray) -> list[int]:
    """
    Viterbi algorithm:
      x: observed labels (ints 0..K-1)
      A: transition probs (KxK), A[prev, cur]
      B: emission probs (KxK), B[y, x] = P(x|y)
      pi: initial distribution (K,)
    Returns:
      y_hat: MAP hidden state sequence (ints)
    """
    K = A.shape[0]   # Number of states
    T = len(x)
    if T == 0:
        return []
    # Convert probs into log probs
    logA = np.log(np.clip(A, 1e-300, None))
    logB = np.log(np.clip(B, 1e-300, None))
    logpi = np.log(np.clip(pi, 1e-300, None))
    # Best log score of any path ending in state y at time t and best prev state that led to y at t
    dp = np.full((T, K), -np.inf, dtype=np.float64)
    back = np.zeros((T, K), dtype=np.int32)
    # Initialization
    x0 = int(x[0])
    dp[0, :] = logpi + logB[:, x0]

    # Dynamic programming forward pass
    for t in range(1, T):
        xt = int(x[t])
        for y in range(K): # Best incoming path for each current hidden state y
            scores = dp[t - 1, :] + logA[:, y]  # Score of coming into y from every prev state
            best_prev = int(np.argmax(scores))
            dp[t, y] = scores[best_prev] + logB[y, xt]  # Best total score
            back[t, y] = best_prev

    # Backtrack
    yT = int(np.argmax(dp[T - 1, :]))
    # Output sequence
    y_hat = [0] * T
    y_hat[T - 1] = yT
    for t in range(T - 2, -1, -1):  # Follow backpointers from end to start
        y_hat[t] = int(back[t + 1, y_hat[t + 1]])

    return y_hat

# ----------------------------
# Forward-Backward marginals (sum-product BP on chain) with scaling
# ----------------------------
def forward_backward_marginals(x: list[int], A: np.ndarray, B: np.ndarray, pi: np.ndarray) -> np.ndarray:
    """
    Returns gamma[t,y] = P(y_t=y | x) using forward-backward with per-step scaling.
    """
    K = A.shape[0]
    T = len(x)
    if T == 0:  # Empty sequence
        return np.zeros((0, K), dtype=np.float64)
    # Scaled forward message up to time t and scaling factor at t
    alpha = np.zeros((T, K), dtype=np.float64)
    c = np.zeros(T, dtype=np.float64)
    # Init forward
    alpha[0, :] = pi * B[:, int(x[0])]
    c[0] = alpha[0, :].sum()
    alpha[0, :] /= max(c[0], 1e-12)

    # Rorward pass
    for t in range(1, T):
        xt = int(x[t])
        alpha[t, :] = (alpha[t - 1, :] @ A) * B[:, xt]  # Predict next state distribution and apply emission likelhood
        c[t] = alpha[t, :].sum()
        alpha[t, :] /= max(c[t], 1e-12)  # Normalize using scaling factor
    # Scaled backward message from future observations
    beta = np.zeros((T, K), dtype=np.float64)
    beta[T - 1, :] = 1.0

    # Backward pass
    for t in range(T - 2, -1, -1):
        xt1 = int(x[t + 1])  # Observation at next time step
        beta[t, :] = (A * (B[:, xt1] * beta[t + 1, :])[None, :]).sum(axis=1)
        beta[t, :] /= max(c[t + 1], 1e-12)  # Scaled message

    gamma = alpha * beta
    gamma /= np.clip(gamma.sum(axis=1, keepdims=True), 1e-12, None)
    return gamma

def decode_from_marginals(gamma: np.ndarray) -> list[int]:
    """
    Per-time-step decode from marginals: y_hat[t] = argmax_y gamma[t,y].
    (This is NOT the same as Viterbi MAP sequence.)
    """
    if gamma.shape[0] == 0:
        return []
    return [int(np.argmax(gamma[t])) for t in range(gamma.shape[0])]

# ----------------------------
# Evaluate Viterbi + Marginals
# ----------------------------
def evaluate_hmm_viterbi(examples: list, A: np.ndarray, eps: float, noise_type: str, num_states: int = 25) -> dict:
    """
    Evaluate HMM MAP decode (Viterbi).
    """
    pi = np.full(num_states, 1.0 / num_states, dtype=np.float64)  # Uniform prior over initial state
    B = emission_uniform(num_states, eps)   # Emission model from corruption level

    accs, changes = [], []
    for ex in examples:
        y = ex.y   # Clean sequence
        x = corrupt(y, noise_type=noise_type, eps=eps)  # Noisy observed sequence
        y_hat = viterbi_decode(x, A=A, B=B, pi=pi)  # Best hidden sequence recovered
        accs.append(accuracy_seq(y, y_hat))
        changes.append(change_rate_seq(y_hat))

    return {
        "acc_mean": float(np.mean(accs)),
        "acc_std": float(np.std(accs)),
        "change_mean": float(np.mean(changes)),
        "change_std": float(np.std(changes)),
        "num_songs": int(len(examples)),
    }

def evaluate_hmm_marginals(examples: list, A: np.ndarray, eps: float, noise_type: str, num_states: int = 25) -> dict:
    """
    Evaluate HMM marginals (forward-backward) + per-time argmax decode.
    Adds confidence = mean_t max_y gamma[t,y].
    """
    pi = np.full(num_states, 1.0 / num_states, dtype=np.float64)  # Uniform initial dist
    B = emission_uniform(num_states, eps)   # Emission model from corruption level

    accs, changes, confs = [], [], []
    for ex in examples:
        y = ex.y
        x = corrupt(y, noise_type=noise_type, eps=eps)
        gamma = forward_backward_marginals(x, A=A, B=B, pi=pi)  # Posterior marginals for each time/state
        y_hat = decode_from_marginals(gamma)   # Independent per-time-step decode

        accs.append(accuracy_seq(y, y_hat))
        changes.append(change_rate_seq(y_hat))
        confs.append(float(np.mean(np.max(gamma, axis=1))))

    return {
        "acc_mean": float(np.mean(accs)),
        "acc_std": float(np.std(accs)),
        "change_mean": float(np.mean(changes)),
        "change_std": float(np.std(changes)),
        "conf_mean": float(np.mean(confs)),
        "conf_std": float(np.std(confs)),
        "num_songs": int(len(examples)),
    }

