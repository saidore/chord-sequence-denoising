# Evaluation wrapper
# ----------------------------
def evaluate_heuristic(examples: list,
                       eps: float,
                       noise_type: str,
                       method: str,
                       window: int = 5) -> dict:
    """
    Corrupt clean y to get x, denoise x with chosen heuristic, then evaluate vs y.
    method: 'none', 'spike', 'majority'
    """
    accs = []
    changes = []

    for ex in examples:
        y = ex.y   # Clean labels
        x = corrupt(y, noise_type=noise_type, eps=eps)   # Noisy labels

        if method == "none":
            y_hat = x     # No denoise baseline
        elif method == "spike":
            y_hat = denoise_spike_removal(x)  # Spike removal
        elif method == "majority":
            y_hat = denoise_majority_filter(x, window=window)   # Majority filter
        else:
            raise ValueError(f"Unknown method: {method}")

        accs.append(accuracy_seq(y, y_hat)) # Accuracy vs clean
        changes.append(change_rate_seq(y_hat))    # Smoothness

    return {
        "acc_mean": float(np.mean(accs)),
        "acc_std": float(np.std(accs)),
        "change_mean": float(np.mean(changes)),
        "change_std": float(np.std(changes)),
        "num_songs": int(len(examples)),
    }

