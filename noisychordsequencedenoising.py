def list_all_files(root_dir: str) -> List[str]:
    files = []
    for base, _, fnames in os.walk(root_dir):  # Scan all subdirs
        for f in fnames:
            files.append(os.path.join(base, f))   # Add full path
    return files

def find_annotation_files(dataset_dir: str) -> Dict[str, List[str]]:
    """
    Tries to find likely chord/beat annotation files by extension and name.
    Returns dict with keys like 'lab', 'beats', 'json', etc.
    """
    all_files = list_all_files(dataset_dir)    # Get all paths
    buckets = {"lab": [], "beats": [], "chords_json": [], "metadata": []}  # Group paths

    for p in all_files:
        pl = p.lower()
        if pl.endswith(".lab"):
            buckets["lab"].append(p)     # Common chord segment format
        elif "beat" in pl and (pl.endswith(".txt") or pl.endswith(".csv") or pl.endswith(".beats")):
            buckets["beats"].append(p)     # Beat times often stored as text
        elif pl.endswith(".json") and ("chord" in pl or "billboard" in pl):
            buckets["chords_json"].append(p)   # Some packs store chord segments as JSON
        elif pl.endswith(".csv") and ("index" in pl or "meta" in pl):
            buckets["metadata"].append(p)    # Metadata index files

    return buckets

