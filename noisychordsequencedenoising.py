# ----------------------------
# Chain graph edges
# ----------------------------
def chain_edge_index(T: int) -> torch.Tensor:
    if T < 2:
        return torch.empty((2, 0), dtype=torch.long)    # No edges
    src = torch.arange(0, T - 1, dtype=torch.long)   # 0..T-2
    dst = torch.arange(1, T, dtype=torch.long)   # 1..T-1
    e1 = torch.stack([src, dst], dim=0)    # Forward edges
    e2 = torch.stack([dst, src], dim=0)   # Backward edges
    return torch.cat([e1, e2], dim=1)  # Bidirectional chain

# ----------------------------
# Dataset: returns x_context (T x 3) and y (T)
# ----------------------------
class ChordChainDataset(torch.utils.data.Dataset):
    """
    Produces PyG graphs per song:
      - data.x_context: LongTensor [T, 3] with [x_prev, x_cur, x_next]
      - data.y:         LongTensor [T] clean labels
      - data.edge_index: chain edges
    """
    def __init__(self, examples, noise_levels, noise_types, mode="train"):
        self.examples = examples    # SongExample list
        self.noise_levels = noise_levels   # eps list
        self.noise_types = noise_types # Noise type list
        self.mode = mode     # train/eval mode

    def __len__(self) -> int:
        return len(self.examples)  # Number of songs

    def __getitem__(self, idx: int) -> Data:
        ex = self.examples[idx]  # Pick song
        y = ex.y    # Clean labels
        T = len(y)

        eps = random.choice(self.noise_levels) if self.mode == "train" else self.noise_levels[0]
        ntype = random.choice(self.noise_types) if self.mode == "train" else self.noise_types[0]
        x = corrupt(y, noise_type=ntype, eps=eps)              # Noisy labels
        # Build prev/cur/next context with PAD at boundaries
        x_prev = [PAD_CLASS] + x[:-1]        # Shift right
        x_cur  = x[:]      # Current
        x_next = x[1:] + [PAD_CLASS]          # Shift left

        x_context = torch.tensor(list(zip(x_prev, x_cur, x_next)), dtype=torch.long)  # [T,3]
        y_tensor = torch.tensor(y, dtype=torch.long)           # [T]

        edge_index = chain_edge_index(T)  # Chain edges

        data = Data(x_context=x_context, y=y_tensor, edge_index=edge_index)
        data.num_nodes = T
        data.seq_len = T
        data.eps = float(eps)
        data.ntype = str(ntype)
        return data

# ----------------------------
# Model: embed prev/cur/next separately (shared embedding), concat -> GraphSAGE -> logits
# ----------------------------
class GNNChordDenoiser(nn.Module):
    """
    Input: x_context [N,3] ints
    - Embed each column -> [N, embed_dim]
    - Concat -> [N, 3*embed_dim]
    - GraphSAGE layers -> [N, hidden_dim]
    - Linear -> [N, NUM_CLASSES]
    """
    def __init__(self, vocab_size: int, num_classes: int = 25, embed_dim: int = 64,
                 hidden_dim: int = 128, num_layers: int = 2, dropout: float = 0.2):
        super().__init__()
        self.embed = nn.Embedding(vocab_size, embed_dim)       # Includes PAD token
        in_dim = 3 * embed_dim      # Prev+cur+next concat
        self.convs = nn.ModuleList()  # Message passing layers
        self.convs.append(SAGEConv(in_dim, hidden_dim))         # First conv
        for _ in range(num_layers - 1):
            self.convs.append(SAGEConv(hidden_dim, hidden_dim)) # Deeper convs

        self.lin = nn.Linear(hidden_dim, num_classes)  # Classifier head
        self.dropout = dropout       # Dropout prob

    def forward(self, data: Data) -> torch.Tensor:
        xc = data.x_context     # [N,3]
        edge_index = data.edge_index   # Edges
        # Embed prev/cur/next and concatenate
        e_prev = self.embed(xc[:, 0])  # [N, D]
        e_cur  = self.embed(xc[:, 1])  # [N, D]
        e_next = self.embed(xc[:, 2])  # [N, D]
        h = torch.cat([e_prev, e_cur, e_next], dim=-1)  # [N, 3D]
        # Message passing
        for conv in self.convs:
            h = conv(h, edge_index)  # Aggregate neighbors
            h = F.relu(h)       # Nonlinearity
            h = F.dropout(h, p=self.dropout, training=self.training)  # Regularize
        logits = self.lin(h)   # [N, C]
        return logits

