RUNTIME_N = min(10, len(test_ex))               # Number of songs to time
RUNTIME_EPS = 0.30                              # Moderate noise
RUNTIME_NOISE = "uniform"                       # Pick one noise type
B = emission_uniform(NUM_CLASSES, RUNTIME_EPS) # HMM emission

runtime_rows = []                               # Store runtime results

for i in range(RUNTIME_N):                      # Loop test songs
    y = test_ex[i].y                            # Clean sequence
    x = corrupt(y, noise_type=RUNTIME_NOISE, eps=RUNTIME_EPS)  # Corrupt sequence

    # Time HMM-Viterbi
    t0 = time.perf_counter()                    # Start timer
    _ = viterbi_decode(x, A=A_final, B=B, pi=pi_final)
    t1 = time.perf_counter()                    # Stop timer
    vit_time = t1 - t0                          # Elapsed

    # Time HMM-Marginal
    t0 = time.perf_counter()                    # Start timer
    gamma = forward_backward_marginals(x, A=A_final, B=B, pi=pi_final)
    _ = decode_from_marginals(gamma)
    t1 = time.perf_counter()                    # Stop timer
    mar_time = t1 - t0                          # Elapsed

    # Time GNN-MIX
    t0 = time.perf_counter()                    # Start timer
    _ = gnn_predict_from_noisy_sequence(model_mix, x)
    t1 = time.perf_counter()                    # Stop timer
    gnn_time = t1 - t0                          # Elapsed

    runtime_rows.append({                       # Save runtimes
        "song_index": i,
        "length": len(y),
        "hmm_viterbi_sec": vit_time,
        "hmm_marginal_sec": mar_time,
        "gnn_mix_sec": gnn_time,
    })

runtime_df = pd.DataFrame(runtime_rows)         # Build DataFrame
runtime_df.to_csv(FINAL_DIR / "runtime_table.csv", index=False)  # Save raw runtimes

