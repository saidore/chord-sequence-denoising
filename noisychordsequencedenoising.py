@torch.no_grad()
def gnn_predict_from_noisy_sequence(model, x_seq):
    """Run one trained GNN on one already-corrupted sequence."""
    model.eval()

    T = len(x_seq)
    if T == 0:
        return []

    x_prev = [PAD_CLASS] + x_seq[:-1]
    x_cur  = x_seq[:]
    x_next = x_seq[1:] + [PAD_CLASS]

    x_context = torch.tensor(
        list(zip(x_prev, x_cur, x_next)),
        dtype=torch.long
    )

    data = Data(
        x_context=x_context,
        edge_index=chain_edge_index(T)
    )
    data.num_nodes = T
    data = data.to(device)

    logits = model(data)
    y_hat = logits.argmax(dim=-1).cpu().tolist()
    return y_hat

